/** 결제 이력 단건 */
export interface PaymentRecord {
  /** 고유 결제 ID */
  id: string;
  /** 결제 일시 (ISO 8601) */
  date: string;
  /** 결제한 개월 수 */
  months: number;
  /** 결제 금액 (원) */
  amount: number;
  /** 플랜명 (예: 'tier_premium') */
  plan: string;
  /** 이 결제로 연장된 시작일 */
  periodFrom: string;
  /** 이 결제로 연장된 종료일 */
  periodTo: string;
}

/** 환불 정책 — 이용 비율에 따른 공정위 기준 */
export type RefundStatus = 'pending' | 'approved' | 'rejected';

export interface RefundRequest {
  status: RefundStatus;
  /** 환불 신청일 (ISO 8601) */
  requestedAt: string;
  /** 신청 사유 */
  reason: string;
  /** 환불 예상금액 (원, 공정위 기준 계산) */
  refundAmount: number;
  /** 환불 비율 설명 */
  refundRatioLabel: string;
  /** 처리 일시 */
  processedAt?: string;
  /** 거부 사유 (관리자 입력) */
  rejectedReason?: string;
}

